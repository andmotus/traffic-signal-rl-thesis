"""
Regenerate every table, figure and reported number of the thesis analysis.

    python analysis/run_all.py

Writes analysis/output/RESULTS.md (all tables and numbers, formatted as in the thesis),
analysis/output/tables/*.csv (full precision) and analysis/output/figures/*.png.
"""
import platform
import time

import matplotlib
import numpy
import openpyxl
import scipy
import statsmodels

import appendix
import h1_learned_vs_fixed
import h2_state_comparison
import h4_co2_national
from common import OUT, SEED, print_utf8


def main():
    start = time.time()
    sections = [h1_learned_vs_fixed.main(), h2_state_comparison.main(), h4_co2_national.main(), appendix.main()]
    header = "\n".join([
        "# Results of the thesis analysis",
        "",
        "Generated by `analysis/run_all.py` from the run logs in `RESCO/results/` and the data in `docs/`.",
        "Do not edit by hand; rerun the script instead.",
        "",
        f"Python {platform.python_version()}, numpy {numpy.__version__}, scipy {scipy.__version__}, "
        f"statsmodels {statsmodels.__version__}, matplotlib {matplotlib.__version__}, openpyxl {openpyxl.__version__}; "
        f"random seed {SEED}.",
    ])
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "RESULTS.md").write_text(header + "\n\n" + "\n\n".join(sections) + "\n", encoding="utf-8")
    print_utf8(f"Wrote {OUT / 'RESULTS.md'}, tables and figures in {time.time() - start:.0f} s")


if __name__ == "__main__":
    main()
